#!/usr/bin/env python3
"""Summarize the supplied 1 ms open/closed pressure recordings.

The script intentionally uses only the Python standard library so the report can
be regenerated on the host used for the C model tests.
"""

from __future__ import annotations

import csv
import pathlib
import statistics
import sys


ROOT = pathlib.Path(__file__).resolve().parents[1]
OPEN_FILES = (
    ROOT / "docs/data_deg/open-8-10-12_rpm.csv",
    ROOT / "docs/data_deg/open-15-20_rpmp.csv",
)
CLOSED_FILE = ROOT / "docs/data_deg/close-50-80-100-120-140_bar_deg.csv"
REPORT_FILE = ROOT / "docs/pressure-model-calibration.md"


def read_rows(path: pathlib.Path) -> list[dict[str, float]]:
    with path.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        return [{key: float(value) for key, value in row.items()} for row in reader]


def segments(rows: list[dict[str, float]], key: str) -> list[tuple[int, int, float]]:
    if not rows:
        return []
    result: list[tuple[int, int, float]] = []
    start = 0
    value = rows[0][key]
    for index in range(1, len(rows)):
        if rows[index][key] != value:
            result.append((start, index, value))
            start = index
            value = rows[index][key]
    result.append((start, len(rows), value))
    return result


def mean(values: list[float]) -> float:
    return statistics.fmean(values) if values else 0.0


def stddev(values: list[float]) -> float:
    return statistics.pstdev(values) if len(values) > 1 else 0.0


def open_summary() -> list[dict[str, float]]:
    result: list[dict[str, float]] = []
    for path in OPEN_FILES:
        rows = read_rows(path)
        for start, end, rpm in segments(rows, "rTargetSpeedRPM"):
            if rpm <= 0.0:
                continue
            section = rows[start:end]
            tail = section[-2000:]
            pressure = [row["rActPressureFiltered"] for row in section]
            tail_pressure = [row["rActPressureFiltered"] for row in tail]
            tail_raw = [row["rActPressureRaw"] for row in tail]
            tail_rpm = [row["rActRawSpeedRPM"] for row in tail]
            tail_torque = [row["rActTorquePercent"] for row in tail]
            result.append(
                {
                    "rpm": rpm,
                    "samples": float(len(section)),
                    "pressure_1s_bar": pressure[min(999, len(pressure) - 1)],
                    "pressure_5s_bar": pressure[min(4999, len(pressure) - 1)],
                    "tail_mean_bar": mean(tail_pressure),
                    "tail_std_bar": stddev(tail_pressure),
                    "tail_p2p_bar": max(tail_pressure) - min(tail_pressure),
                    "tail_raw_std_bar": stddev(tail_raw),
                    "tail_feedback_rpm": mean(tail_rpm),
                    "tail_feedback_rpm_std": stddev(tail_rpm),
                    "tail_torque_percent": mean(tail_torque),
                }
            )
    return sorted(result, key=lambda item: item["rpm"])


def closed_summary() -> list[dict[str, float]]:
    rows = read_rows(CLOSED_FILE)
    result: list[dict[str, float]] = []
    for start, end, target in segments(rows, "rTargetPressure"):
        if target <= 0.0:
            continue
        section = rows[start:end]
        tail = section[-2000:]
        pressure = [row["rActPressureFiltered"] for row in section]
        tail_pressure = [row["rActPressureFiltered"] for row in tail]
        result.append(
            {
                "target_bar": target,
                "samples": float(len(section)),
                "peak_bar": max(pressure),
                "tail_mean_bar": mean(tail_pressure),
                "tail_std_bar": stddev(tail_pressure),
                "tail_p2p_bar": max(tail_pressure) - min(tail_pressure),
                "tail_target_rpm": mean([row["rTargetSpeedRPM"] for row in tail]),
                "tail_feedback_rpm": mean([row["rActRawSpeedRPM"] for row in tail]),
                "tail_flow_lmin": mean([row["rPIDControllerOutputFlow"] for row in tail]),
                "tail_torque_percent": mean([row["rActTorquePercent"] for row in tail]),
            }
        )
    return result


def render(open_data: list[dict[str, float]], closed_data: list[dict[str, float]]) -> str:
    lines = [
        "# Pressure model calibration evidence",
        "",
        "This report is generated by `scripts/analyze_pressure_model_data.py`. Each row is",
        "treated as one 1 ms scan because the supplied degree-export files do not carry a",
        "timestamp column. The report describes measured behavior; it is not a claim that",
        "the machine has a unique parameter set identifiable from these records alone.",
        "",
        "## Open-loop dead-head evidence",
        "",
        "The pump speed command is stepped to 8, 10, 12, 15, and 20 RPM while the pressure",
        "target remains zero. The tail window is the final 2000 samples of each positive-speed",
        "segment. The measured pressure envelope grows with pressure and speed, while feedback",
        "speed has a several-RPM spread and torque is negative under load.",
        "",
        "| Set RPM | Samples | P(1 s) bar | P(5 s) bar | Tail mean bar | Tail p-p bar | Feedback RPM | Torque % |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for item in open_data:
        lines.append(
            "| {rpm:.0f} | {samples:.0f} | {pressure_1s_bar:.2f} | {pressure_5s_bar:.2f} | "
            "{tail_mean_bar:.2f} | {tail_p2p_bar:.2f} | {tail_feedback_rpm:.2f} | "
            "{tail_torque_percent:.2f} |".format(**item)
        )
    lines.extend(
        [
            "",
            "The model therefore uses one trapped-oil pressure state, a speed-dependent leakage",
            "balance, and a separate angle-synchronous measurement disturbance. A single",
            "independent pressure curve per speed is not justified by the data.",
            "",
            "## Closed-loop RBF-PID evidence",
            "",
            "The closed-loop recording contains pressure targets of 50, 80, 100, 120, and 140 bar.",
            "The same 2000-sample tail window is used for hold metrics.",
            "",
            "| Target bar | Samples | Peak bar | Tail mean bar | Tail p-p bar | Target RPM | Feedback RPM | Flow L/min | Torque % |",
            "|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
        ]
    )
    for item in closed_data:
        lines.append(
            "| {target_bar:.0f} | {samples:.0f} | {peak_bar:.2f} | {tail_mean_bar:.2f} | "
            "{tail_p2p_bar:.2f} | {tail_target_rpm:.2f} | {tail_feedback_rpm:.2f} | "
            "{tail_flow_lmin:.3f} | {tail_torque_percent:.2f} |".format(**item)
        )
    lines.extend(
        [
            "",
            "## Embedded calibration decisions",
            "",
            "- `physical.chamber_volume_m3 = 7.0e-4` and `gas_fraction = 2.0e-5` reproduce the",
            "  approximately one-second pressure rise seen in the open-loop sections.",
            "- Pump, outlet, and cylinder leakage defaults are `3.4e-13`, `1.7e-13`, and",
            "  `1.7e-13 m^3/(Pa s)`, which set the observed 8--20 RPM pressure platform.",
            "- The visible pressure layer uses a 5% pressure-relative periodic envelope with",
            "  13th/26th/39th shaft orders. The process ripple can be disabled by setting",
            "  `flow_ripple_ratio = 0` for deterministic controller tests.",
            "- Torque is derived from pressure differential and pump displacement, with the",
            "  resisting-load sign used by the recordings. It remains a trend signal, not a",
            "  separately fitted state.",
            "",
            "## Limits",
            "",
            "The recordings do not identify line inertance, valve-open flow, temperature, or",
            "cylinder load independently. Those mechanisms remain explicit parameters, but this",
            "profile is only validated for the supplied 1 ms dead-head and pressure-hold tests.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    output = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else REPORT_FILE
    open_data = open_summary()
    closed_data = closed_summary()
    if len(open_data) != 5 or len(closed_data) < 5:
        raise RuntimeError("expected five open-loop and at least five closed-loop segments")
    output.write_text(render(open_data, closed_data), encoding="utf-8")
    print(f"wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
